async function captureGit(root, artifactDir) {
  const names = {
    status: ["git-status.porcelain.z", "git-status.stderr.log"],
    unstaged: ["git-diff.unstaged.patch", "git-diff.unstaged.stderr.log"],
    staged: ["git-diff.staged.patch", "git-diff.staged.stderr.log"],
  };
  const calls = [
    ["status", ["status", "--porcelain=v1", "-z", "--untracked-files=all"]],
    ["unstaged", ["diff", "--no-ext-diff", "--binary", "--full-index"]],
    ["staged", ["diff", "--cached", "--no-ext-diff", "--binary", "--full-index"]],
  ];
  const results = {};
  for (const [label, args] of calls) {
    results[label] = await runCapture("git", ["--no-optional-locks", ...args], {
      cwd: root,
      stdoutPath: path.join(artifactDir, names[label][0]),
      stderrPath: path.join(artifactDir, names[label][1]),
      timeoutMs: DEFAULT_TIMEOUT_MS,
    });
  }
  const statusBuffer = await fsp.readFile(path.join(artifactDir, names.status[0]));
  return { results, statusBuffer, names };
}

function validatorConfig(value) {
  if (!value || typeof value !== "object" || Array.isArray(value)) fail("validator must be an object", "E_VALIDATOR_CONFIG");
  if (typeof value.executable !== "string" || value.executable.length === 0) fail("validator executable is required", "E_VALIDATOR_CONFIG");
  if (!Array.isArray(value.args) || value.args.some((arg) => typeof arg !== "string")) fail("validator args must be an array of strings", "E_VALIDATOR_CONFIG");
  return {
    name: typeof value.name === "string" && value.name ? value.name : value.executable,
    executable: value.executable,
    args: [...value.args],
    cwd: value.cwd,
  };
}

async function loadValidators(root, options) {
  const values = [];
  if (options.validatorsFile) {
    const raw = JSON.parse((await readOwnedFile(root, options.validatorsFile, "validators file")).toString("utf8"));
    const list = Array.isArray(raw) ? raw : raw?.validators;
    if (!Array.isArray(list)) fail("validators file must contain an array or { validators: [] }", "E_VALIDATOR_CONFIG");
    values.push(...list);
  }
  if (options.validatorJson) {
    for (const raw of options.validatorJson) values.push(JSON.parse(raw));
  }
  return values.map(validatorConfig);
}

function validatorCwd(root, cwd) {
  if (cwd === undefined || cwd === null || cwd === "") return root;
  const rel = assertRelativeInput(cwd, "validator cwd");
  const absolute = absoluteFromRelative(root, rel);
  assertInside(root, absolute, "validator cwd");
  return absolute;
}

async function runGate(options) {
  const root = await gitRoot(await realDirectory(options.root, "root"));
  const baselineRelative = assertRelativeInput(options.baseline, "baseline");
  const baseline = JSON.parse((await readOwnedFile(root, baselineRelative, "baseline")).toString("utf8"));
  if (baseline.schemaVersion !== SNAPSHOT_SCHEMA) fail("baseline is not a dd-efficiency snapshot", "E_BASELINE");
  if (path.resolve(baseline.repoRoot) !== path.resolve(root)) fail("baseline belongs to a different repository root", "E_BASELINE");
  const allowlist = normalizeAllowlist(options.allow);
  const exclusions = [baselineRelative];
  const artifactRelative = assertRelativeInput(options.artifactDir || `.dd-efficiency/runs/gate-${Date.now()}-${process.pid}-${crypto.randomBytes(3).toString("hex")}`, "artifact directory");
  for (const exclusion of options.exclude || []) exclusions.push(assertRelativeInput(exclusion, "exclusion"));
  for (const entry of allowlist) {
    if (pathOverlaps(entry, artifactRelative)) fail(`artifact directory overlaps allowlist entry: ${artifactRelative} / ${entry}`, "E_SCOPE_OVERLAP");
  }
  for (const exclusion of exclusions) {
    if (allowlist.some((entry) => pathOverlaps(entry, exclusion))) fail(`exclusion overlaps allowlist: ${exclusion}`, "E_SCOPE_OVERLAP");
    if (pathOverlaps(exclusion, artifactRelative) && exclusion !== artifactRelative) {
      fail(`artifact directory overlaps an input exclusion: ${artifactRelative} / ${exclusion}`, "E_SCOPE_OVERLAP");
    }
  }
  // The fresh helper subtree is an explicit, narrowly recorded exclusion.
  // It is added only after overlap checks so an allowlist can never hide it.
  exclusions.push(artifactRelative);
  const validators = await loadValidators(root, options);
  const artifactDir = await createFreshDirectory(root, artifactRelative);
  const validatorResults = [];
  for (let index = 0; index < validators.length; index += 1) {
    const validator = validators[index];
    const prefix = `validator-${String(index + 1).padStart(2, "0")}`;
    const cwd = validatorCwd(root, validator.cwd);
    if (validator.cwd) await assertNoReparseCrossing(root, validator.cwd, { allowMissing: false, includeFinal: true });
    const result = await runCapture(validator.executable, validator.args, {
      cwd,
      stdoutPath: path.join(artifactDir, `${prefix}.stdout.log`),
      stderrPath: path.join(artifactDir, `${prefix}.stderr.log`),
      timeoutMs: options.timeoutMs,
    });
    validatorResults.push({
      name: validator.name, status: result.spawnError || result.timedOut || result.logDrainTimedOut || result.code !== 0 ? "FAIL" : "PASS",
      exitCode: result.code, signal: result.signal, spawnError: result.spawnError, timedOut: result.timedOut,
      logDrainTimedOut: result.logDrainTimedOut,
      stdoutBytes: result.stdoutBytes, stderrBytes: result.stderrBytes,
      stdoutPreview: result.stdoutPreview, stderrPreview: result.stderrPreview,
      stdoutPath: `${artifactRelative}/${prefix}.stdout.log`, stderrPath: `${artifactRelative}/${prefix}.stderr.log`,
      processTreeTermination: result.processTreeTermination,
    });
  }
  const captured = await captureGit(root, artifactDir);
  const current = await inventory(root, { statusBuffer: captured.statusBuffer });
  const currentIdentity = await gitIdentity(root);
  const allPaths = new Set([...Object.keys(baseline.files || {}), ...current.files, ...await scopedFiles(root, allowlist)]);
  const changed = [];
  const unchangedExistingDirty = [];
  const diagnostics = [];
  const fingerprintChanges = [];
  for (const relative of [...allPaths].sort()) {
    if (exclusions.some((exclusion) => pathMatches(relative, exclusion))) continue;
    const before = baseline.files?.[relative] || { kind: "missing" };
    const after = await fingerprint(root, relative);
    if (["error", "directory", "special"].includes(after.kind)) diagnostics.push(`${relative}: unsupported fingerprint ${after.kind}: ${after.error || ""}`);
    if (!fingerprintsEqual(before, after)) {
      changed.push(relative);
      fingerprintChanges.push({ path: relative, before, after });
    } else if ((baseline.status?.dirtyPaths || []).includes(relative)) {
      unchangedExistingDirty.push(relative);
    }
  }
  const unexpected = changed.filter((relative) => !allowlist.some((entry) => pathMatches(relative, entry)));
  const allowedChanged = changed.filter((relative) => !unexpected.includes(relative));
  const identityFailures = [];
  for (const field of ["head", "branch", "indexHash"]) {
    if ((baseline.git?.[field] ?? null) !== (currentIdentity[field] ?? null)) {
      identityFailures.push(`${field}: expected ${baseline.git?.[field] ?? "null"}, current ${currentIdentity[field] ?? "null"}`);
    }
  }
  await fsp.writeFile(path.join(artifactDir, "fingerprint-changes.json"), `${JSON.stringify(fingerprintChanges, null, 2)}\n`, { flag: "wx" });
  const rawUnexpected = posixPath(path.join(artifactRelative, "unexpected-paths.json"));
  const rawDiagnostics = posixPath(path.join(artifactRelative, "diagnostics.json"));
  const rawIdentityFailures = posixPath(path.join(artifactRelative, "identity-failures.json"));
  const rawUnchangedDirty = posixPath(path.join(artifactRelative, "unchanged-dirty.json"));
  await fsp.writeFile(absoluteFromRelative(root, rawUnexpected), `${JSON.stringify(unexpected, null, 2)}\n`, { flag: "wx" });
  await fsp.writeFile(absoluteFromRelative(root, rawDiagnostics), `${JSON.stringify(diagnostics, null, 2)}\n`, { flag: "wx" });
  await fsp.writeFile(absoluteFromRelative(root, rawIdentityFailures), `${JSON.stringify(identityFailures, null, 2)}\n`, { flag: "wx" });
  await fsp.writeFile(absoluteFromRelative(root, rawUnchangedDirty), `${JSON.stringify(unchangedExistingDirty, null, 2)}\n`, { flag: "wx" });
  const failedValidators = validatorResults.filter((item) => item.status !== "PASS");
  const gitCaptureFailure = Object.entries(captured.results)
    .filter(([, result]) => result.spawnError || result.timedOut || result.logDrainTimedOut || result.code !== 0)
    .map(([label, result]) => `${label}: ${result.spawnError?.message || result.signal || result.code}`);
  const status = unexpected.length === 0 && diagnostics.length === 0 && identityFailures.length === 0 && failedValidators.length === 0 && gitCaptureFailure.length === 0 ? "PASS" : "FAIL";
  const summary = {
    schemaVersion: SUMMARY_SCHEMA,
    command: "gate",
    status,
    repoRoot: root,
    counts: {
      changed: changed.length,
      allowedChanged: allowedChanged.length,
      unexpected: unexpected.length,
      unchangedExistingDirty: unchangedExistingDirty.length,
      identityFailures: identityFailures.length,
      validators: validatorResults.length,
      validatorFailures: failedValidators.length,
      diagnostics: diagnostics.length,
    },
    allowlist,
    exclusions,
    identityFailures: boundedItems(identityFailures, rawIdentityFailures),
    unexpectedPaths: boundedItems(unexpected, rawUnexpected),
    unchangedExistingDirty: boundedItems(unchangedExistingDirty, rawUnchangedDirty),
    diagnostics: boundedItems(diagnostics, rawDiagnostics),
    validators: validatorResults,
    gitCaptureFailure,
    coverageLimits: [
      "Ignored paths outside explicitly checked scopes are not covered; this is not a whole-filesystem guarantee.",
      "Process-tree termination is child-only; provider/adapters must enforce their own tree watchdog where needed.",
    ],
    rawPaths: [
      posixPath(path.join(artifactRelative, "git-status.porcelain.z")),
      posixPath(path.join(artifactRelative, "git-status.stderr.log")),
      posixPath(path.join(artifactRelative, "git-diff.unstaged.patch")),
      posixPath(path.join(artifactRelative, "git-diff.unstaged.stderr.log")),
      posixPath(path.join(artifactRelative, "git-diff.staged.patch")),
      posixPath(path.join(artifactRelative, "git-diff.staged.stderr.log")),
      rawUnexpected,
      rawDiagnostics,
      rawIdentityFailures,
      rawUnchangedDirty,
      `${artifactRelative}/fingerprint-changes.json`,
    ],
    artifactDir: artifactRelative,
    summaryPath: posixPath(path.join(artifactRelative, "summary.json")),
  };
  return writeSummary(artifactDir, root, artifactRelative, summary, options.maxSummaryBytes);
}

