#!/usr/bin/env node

/**
 * Small, dependency-free mechanical helper for the Deliberate Delegate skill.
 *
 * The helper is deliberately a Lead-side tool.  It records mechanical
 * evidence and waits for one already-authorized adapter process; it never
 * makes a planner decision, changes project state, or runs a model loop.
 */

import crypto from "node:crypto";
import fs from "node:fs";
import fsp from "node:fs/promises";
import { pipeline } from "node:stream/promises";
import { pathToFileURL } from "node:url";
import path from "node:path";
import { spawn } from "node:child_process";

const SUMMARY_SCHEMA = "dd-efficiency.summary.v1";
const SNAPSHOT_SCHEMA = "dd-efficiency.snapshot.v1";
const GENERATED_INDEX_MARKER = "<!-- Generated by dd-efficiency index; non-authoritative. -->";
const DEFAULT_SUMMARY_BYTES = 8 * 1024;
const DEFAULT_TIMEOUT_MS = 30 * 60 * 1000;
const OUTPUT_PREVIEW_BYTES = 4096;
const TERMINAL_STATUSES = new Set([
  "completed",
  "failed",
  "timeout",
  "timed_out",
  "cancelled",
  "canceled",
  "stopped",
  "error",
]);
const NONTERMINAL_STATUSES = new Set([
  "pending",
  "running",
  "started",
  "dispatched",
  "in_progress",
  "queued",
]);

function fail(message, code = "E_INVALID") {
  const error = new Error(message);
  error.code = code;
  throw error;
}

function posixPath(value) {
  return String(value).replaceAll("\\", "/");
}

function isAbsoluteAny(value) {
  return path.isAbsolute(value) || path.win32.isAbsolute(value);
}

function assertRelativeInput(value, label) {
  if (typeof value !== "string" || value.length === 0) {
    fail(`${label} must be a non-empty project-relative path`);
  }
  const normalized = posixPath(value);
  if (normalized.split("/").some((part) => part.toLowerCase() === ".git")) fail(`${label} must not target Git metadata`, "E_PATH_ESCAPE");
  if (isAbsoluteAny(value) || normalized.startsWith("/") || normalized.split("/").includes("..") || normalized.includes("\0") || (process.platform === "win32" && normalized !== "." && /[:]|[. ](?:\/|$)/.test(normalized.replace(/^\.\//, "")))) {
    fail(`${label} must not be absolute or contain path traversal: ${value}`, "E_PATH_TRAVERSAL");
  }
  return path.posix.normalize(normalized);
}

async function realDirectory(input, label = "root") {
  const candidate = path.resolve(input || process.cwd());
  let real;
  try {
    real = await fsp.realpath(candidate);
  } catch (error) {
    fail(`${label} does not exist: ${candidate}`, "E_ROOT");
  }
  const stat = await fsp.lstat(real);
  if (!stat.isDirectory()) fail(`${label} is not a directory: ${candidate}`, "E_ROOT");
  return real;
}

function absoluteFromRelative(root, relative) {
  return path.join(root, ...posixPath(relative).split("/"));
}

function assertInside(root, absolute, label = "path") {
  const relative = path.relative(root, absolute);
  if (relative === "" || relative === ".." || relative.startsWith(`..${path.sep}`) || isAbsoluteAny(relative)) {
    fail(`${label} escapes the project root: ${absolute}`, "E_PATH_ESCAPE");
  }
}

async function assertNoReparseCrossing(root, relative, { allowMissing = true, includeFinal = true } = {}) {
  const rel = assertRelativeInput(relative, "path");
  const parts = rel.split("/").filter(Boolean);
  let current = root;
  for (let index = 0; index < parts.length; index += 1) {
    current = path.join(current, parts[index]);
    let stat;
    try {
      stat = await fsp.lstat(current);
    } catch (error) {
      if (error.code === "ENOENT" && allowMissing) return;
      throw error;
    }
    const isLink = stat.isSymbolicLink();
    if (isLink && (includeFinal || index < parts.length - 1)) {
      fail(`symlink/reparse crossing is not allowed for owned path: ${relative}`, "E_SYMLINK");
    }
    if (index < parts.length - 1 && !stat.isDirectory()) {
      fail(`owned path parent is not a directory: ${relative}`, "E_PATH_PARENT");
    }
  }
}

async function ensureParent(root, relative) {
  const rel = assertRelativeInput(relative, "output path");
  const parent = posixPath(path.posix.dirname(rel));
  if (parent === "." || parent === "") return;
  const parts = parent.split("/").filter(Boolean);
  let current = root;
  for (const part of parts) {
    current = path.join(current, part);
    let stat;
    try {
      stat = await fsp.lstat(current);
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
      await fsp.mkdir(current);
      stat = await fsp.lstat(current);
    }
    if (stat.isSymbolicLink() || !stat.isDirectory()) {
      fail(`owned output parent crosses a symlink or is not a directory: ${parent}`, "E_SYMLINK");
    }
  }
}

async function createFreshDirectory(root, relative) {
  const rel = assertRelativeInput(relative, "artifact directory");
  if (rel === "." || rel === "") fail("artifact directory may not be the project root", "E_PATH_ESCAPE");
  const absolute = absoluteFromRelative(root, rel);
  assertInside(root, absolute, "artifact directory");
  await ensureParent(root, rel);
  try {
    await fsp.lstat(absolute);
    fail(`output collision: artifact directory already exists: ${rel}`, "E_OUTPUT_COLLISION");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  await fsp.mkdir(absolute);
  const stat = await fsp.lstat(absolute);
  if (stat.isSymbolicLink() || !stat.isDirectory()) fail(`artifact directory is not owned: ${rel}`, "E_SYMLINK");
  return absolute;
}

async function writeNewFile(root, relative, data) {
  const rel = assertRelativeInput(relative, "output path");
  const absolute = absoluteFromRelative(root, rel);
  assertInside(root, absolute, "output path");
  await ensureParent(root, rel);
  try {
    const stat = await fsp.lstat(absolute);
    if (stat.isSymbolicLink()) fail(`refusing to overwrite symlink: ${rel}`, "E_SYMLINK");
    fail(`output collision: file already exists: ${rel}`, "E_OUTPUT_COLLISION");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  await fsp.writeFile(absolute, data, { flag: "wx" });
  return absolute;
}

async function writeGeneratedIndex(root, relative, data) {
  const rel = assertRelativeInput(relative, "index output");
  const absolute = absoluteFromRelative(root, rel);
  assertInside(root, absolute, "index output");
  await ensureParent(root, rel);
  let exists = false;
  try {
    const stat = await fsp.lstat(absolute);
    exists = true;
    if (stat.isSymbolicLink() || !stat.isFile()) fail(`refusing to overwrite non-file index: ${rel}`, "E_SYMLINK");
    const existing = await fsp.readFile(absolute, "utf8");
    if (!existing.startsWith(`${GENERATED_INDEX_MARKER}\n`)) {
      fail(`refusing to overwrite immutable/non-generated record: ${rel}`, "E_IMMUTABLE");
    }
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (exists) {
    await fsp.writeFile(absolute, data, { flag: "w" });
  } else {
    await fsp.writeFile(absolute, data, { flag: "wx" });
  }
  return absolute;
}

async function readOwnedFile(root, relative, label = "file") {
  const rel = assertRelativeInput(relative, label);
  await assertNoReparseCrossing(root, rel, { allowMissing: false, includeFinal: true });
  const absolute = absoluteFromRelative(root, rel);
  const stat = await fsp.lstat(absolute);
  if (!stat.isFile()) fail(`${label} is not a regular file: ${rel}`, "E_FILE");
  return fsp.readFile(absolute);
}

function sha256Bytes(value) {
  return crypto.createHash("sha256").update(value).digest("hex");
}

async function hashRegularFile(absolute) {
  const hash = crypto.createHash("sha256");
  let size = 0;
  await new Promise((resolve, reject) => {
    const stream = fs.createReadStream(absolute);
    stream.on("data", (chunk) => {
      size += chunk.length;
      hash.update(chunk);
    });
    stream.on("error", reject);
    stream.on("end", resolve);
  });
  return { digest: hash.digest("hex"), size };
}

async function fingerprint(root, relative) {
  const rel = assertRelativeInput(relative, "inventory path");
  const parts = rel.split("/").filter(Boolean);
  let current = root;
  for (let index = 0; index < parts.length; index += 1) {
    current = path.join(current, parts[index]);
    let stat;
    try {
      stat = await fsp.lstat(current);
    } catch (error) {
      if (error.code === "ENOENT") return { kind: "missing" };
      return { kind: "error", error: `${error.code || "read"}: ${error.message}` };
    }
    if (stat.isSymbolicLink()) {
      let target = "";
      try {
        target = await fsp.readlink(current);
      } catch (error) {
        return { kind: "error", error: `${error.code || "readlink"}: ${error.message}` };
      }
      return { kind: "symlink", target, digest: sha256Bytes(`symlink\0${target}`) };
    }
    if (index < parts.length - 1 && !stat.isDirectory()) {
      return { kind: "error", error: "path component is not a directory" };
    }
    if (index === parts.length - 1) {
      if (stat.isDirectory()) return { kind: "directory" };
      if (!stat.isFile()) return { kind: "special" };
      try {
        const hashed = await hashRegularFile(current);
        return { kind: "file", ...hashed, mode: stat.mode };
      } catch (error) {
        return { kind: "error", error: `${error.code || "read"}: ${error.message}` };
      }
    }
  }
  return { kind: "missing" };
}

function fingerprintsEqual(left, right) {
  if (!left || !right || left.kind !== right.kind) return false;
  if (left.kind === "file") return left.digest === right.digest && left.size === right.size && left.mode === right.mode;
  if (left.kind === "symlink") return left.digest === right.digest && left.target === right.target;
  if (left.kind === "error") return left.error === right.error;
  return true;
}

async function drainLogs(logs, streams, timeoutMs = 5000) {
  let timer;
  const timedOut = await Promise.race([
    Promise.all(logs).then(() => false),
    new Promise((resolve) => { timer = setTimeout(() => resolve(true), timeoutMs); }),
  ]);
  clearTimeout(timer);
  if (timedOut) {
    for (const stream of streams) stream.destroy();
    await Promise.all(logs);
  }
  return timedOut;
}

async function runCapture(command, args, { cwd, stdoutPath, stderrPath, timeoutMs = DEFAULT_TIMEOUT_MS } = {}) {
  const stdout = fs.createWriteStream(stdoutPath, { flags: "wx" });
  const stderr = fs.createWriteStream(stderrPath, { flags: "wx" });
  let stdoutBytes = 0;
  let stderrBytes = 0;
  const stdoutPreview = [];
  const stderrPreview = [];
  let timedOut = false;
  let killRequested = false;
  let spawnError = null;
  const started = Date.now();

  const child = spawn(command, args, {
    cwd,
    shell: false,
    windowsHide: true,
    stdio: ["ignore", "pipe", "pipe"],
  });

  const collect = (stream, destination, preview, which) => {
    let seen = 0;
    stream.on("data", (chunk) => {
      const bytes = chunk.length;
      if (which === "stdout") stdoutBytes += bytes;
      else stderrBytes += bytes;
      if (seen < OUTPUT_PREVIEW_BYTES) {
        const kept = chunk.subarray(0, OUTPUT_PREVIEW_BYTES - seen);
        preview.push(kept);
        seen += kept.length;
      }
    });
    // pipeline applies backpressure; log write errors must fail the operation.
    return pipeline(stream, destination).catch((error) => {
      spawnError = { code: error.code || null, message: `log capture: ${error.message}` };
      child.kill();
    });
  };
  const logs = [collect(child.stdout, stdout, stdoutPreview, "stdout"),
    collect(child.stderr, stderr, stderrPreview, "stderr")];

  const result = await new Promise((resolve) => {
    let settled = false;
    let timer;
    const finish = (value) => {
      if (settled) return;
      settled = true;
      if (timer) clearTimeout(timer);
      resolve(value);
    };
    child.once("error", (error) => {
      spawnError = { code: error.code || null, message: error.message };
      finish({ code: null, signal: null, timedOut, killRequested });
    });
    // exit proves the owned process finished; close may wait on descendant pipes.
    child.once("exit", (code, signal) => {
      finish({ code, signal, timedOut, killRequested });
    });
    if (timeoutMs > 0) {
      timer = setTimeout(() => {
        timedOut = true;
        try {
          killRequested = child.kill("SIGKILL");
        } catch (error) {
          killRequested = false;
          spawnError = { code: error.code || null, message: error.message };
        }
      }, timeoutMs);
    }
  });

  const logDrainTimedOut = await drainLogs(logs, [child.stdout, child.stderr, stdout, stderr]);

  return {
    ...result,
    spawnError,
    logDrainTimedOut,
    stdoutBytes,
    stderrBytes,
    stdoutPreview: Buffer.concat(stdoutPreview).toString("utf8"),
    stderrPreview: Buffer.concat(stderrPreview).toString("utf8"),
    durationMs: Date.now() - started,
    processTreeTermination: process.platform === "win32" ? "child-only; descendants are not guaranteed terminated" : "child-only",
  };
}

async function execGit(root, args, { allowFailure = false } = {}) {
  const child = await runTextProcess("git", ["--no-optional-locks", ...args], root);
  if (!allowFailure && child.code !== 0) {
    fail(`git ${args.join(" ")} failed (${child.code ?? child.signal ?? "spawn"}): ${child.stderr.toString("utf8").trim()}`, "E_GIT");
  }
  return child;
}

async function runTextProcess(command, args, cwd) {
  return await new Promise((resolve) => {
    const child = spawn(command, args, { cwd, shell: false, windowsHide: true, stdio: ["ignore", "pipe", "pipe"] });
    const stdout = [];
    const stderr = [];
    child.stdout.on("data", (chunk) => stdout.push(chunk));
    child.stderr.on("data", (chunk) => stderr.push(chunk));
    child.once("error", (error) => resolve({ code: null, signal: null, error, stdout: Buffer.concat(stdout), stderr: Buffer.concat(stderr) }));
    child.once("close", (code, signal) => resolve({ code, signal, stdout: Buffer.concat(stdout), stderr: Buffer.concat(stderr) }));
  });
}

function splitNul(buffer) {
  return buffer.toString("utf8").split("\0").filter((part) => part.length > 0);
}

function parsePorcelain(buffer) {
  const tokens = splitNul(buffer);
  const records = [];
  for (let index = 0; index < tokens.length; index += 1) {
    const token = tokens[index];
    if (token.length < 3) continue;
    const xy = token.slice(0, 2);
    const first = posixPath(token.slice(3));
    const paths = [first];
    if (xy.includes("R") || xy.includes("C")) {
      if (index + 1 < tokens.length) paths.push(posixPath(tokens[++index]));
    }
    records.push({ status: xy, paths });
  }
  return records;
}

function pathSetFromRecords(records) {
  const result = new Set();
  for (const record of records) for (const relative of record.paths) result.add(posixPath(relative));
  return result;
}

async function gitIdentity(root) {
  const headResult = await execGit(root, ["rev-parse", "--verify", "HEAD"], { allowFailure: true });
  const branchResult = await execGit(root, ["symbolic-ref", "--quiet", "--short", "HEAD"], { allowFailure: true });
  // Hash semantic stage entries, not the index's mutable stat/cache extensions.
  const indexResult = await execGit(root, ["ls-files", "--stage", "-z"]);
  const indexHash = sha256Bytes(indexResult.stdout);
  return {
    head: headResult.code === 0 ? headResult.stdout.toString("utf8").trim() : null,
    branch: branchResult.code === 0 ? branchResult.stdout.toString("utf8").trim() : "DETACHED",
    indexHash,
  };
}

async function gitRoot(root) {
  const result = await execGit(root, ["rev-parse", "--show-toplevel"]);
  const actual = await fsp.realpath(result.stdout.toString("utf8").trim());
  if (path.resolve(root) !== path.resolve(actual)) fail("root must be the explicit repository root, not a subdirectory", "E_ROOT");
  return actual;
}

async function gitPathList(root, args) {
  const result = await execGit(root, args);
  return splitNul(result.stdout).map(posixPath);
}

async function inventory(root, { statusBuffer } = {}) {
  const statusResult = statusBuffer
    ? { code: 0, stdout: statusBuffer, stderr: Buffer.alloc(0) }
    : await execGit(root, ["status", "--porcelain=v1", "-z", "--untracked-files=all"]);
  if (statusResult.code !== 0) fail(`unable to read Git status: ${statusResult.stderr.toString("utf8")}`, "E_GIT");
  const statusRecords = parsePorcelain(statusResult.stdout);
  const files = new Set(pathSetFromRecords(statusRecords));
  for (const item of await gitPathList(root, ["ls-tree", "-r", "--name-only", "-z", "HEAD"])) files.add(item);
  for (const item of await gitPathList(root, ["ls-files", "-z", "--cached"])) files.add(item);
  for (const item of await gitPathList(root, ["ls-files", "--others", "--exclude-standard", "-z"])) files.add(item);
  return { statusRecords, files: [...files].sort(), statusBuffer: statusResult.stdout };
}

async function scopedFiles(root, scopes) {
  const found = new Set();
  const visit = async (relative) => {
    await assertNoReparseCrossing(root, relative, { allowMissing: true, includeFinal: false });
    const absolute = absoluteFromRelative(root, relative);
    let stat;
    try { stat = await fsp.lstat(absolute); } catch (error) { if (error.code === "ENOENT") return; throw error; }
    if (stat.isDirectory() && !stat.isSymbolicLink()) {
      for (const entry of await fsp.readdir(absolute)) await visit(`${relative}/${entry}`);
    } else found.add(relative);
  };
  for (const scope of scopes) {
    const relative = assertRelativeInput(scope, "checked scope");
    if (relative === ".") fail("checked scope must be narrower than the repository root", "E_SCOPE_OVERLAP");
    await visit(relative);
  }
  return [...found];
}

async function snapshotData(root, { allow = [] } = {}) {
  const actualRoot = await gitRoot(root);
  const [identity, collected] = await Promise.all([gitIdentity(actualRoot), inventory(actualRoot)]);
  const fileMap = {};
  for (const relative of new Set([...collected.files, ...await scopedFiles(actualRoot, allow)])) fileMap[relative] = await fingerprint(actualRoot, relative);
  const incomplete = Object.entries(fileMap).filter(([, item]) => ["error", "directory", "special"].includes(item.kind));
  if (incomplete.length) fail(`snapshot has unreadable/unsupported paths: ${incomplete.slice(0, 5).map(([name]) => name).join(", ")}`, "E_COVERAGE");
  return {
    schemaVersion: SNAPSHOT_SCHEMA,
    capturedAt: new Date().toISOString(),
    repoRoot: actualRoot,
    git: identity,
    status: {
      records: collected.statusRecords,
      dirtyPaths: [...pathSetFromRecords(collected.statusRecords)].sort(),
      counts: {
        records: collected.statusRecords.length,
        paths: pathSetFromRecords(collected.statusRecords).size,
      },
    },
    files: fileMap,
    checkedScopes: allow,
    coverageLimits: ["Ignored paths outside explicitly checked scopes are not covered; this is not a whole-filesystem guarantee."],
  };
}

function normalizeAllowlist(values) {
  if (!Array.isArray(values) || values.length === 0) fail("at least one exact file or directory must be allowlisted", "E_ALLOWLIST");
  return [...new Set(values.map((value) => assertRelativeInput(value, "allowlist entry").replace(/\/$/, "")))];
}

function pathMatches(candidate, allowed) {
  const value = posixPath(candidate).replace(/^\.\//, "");
  const rule = posixPath(allowed).replace(/^\.\//, "").replace(/\/$/, "");
  if (rule === "." || rule === "") return true;
  return value === rule || value.startsWith(`${rule}/`);
}

function pathOverlaps(left, right) {
  return pathMatches(left, right) || pathMatches(right, left);
}

function boundedItems(items, rawLocator, maxItems = 32, maxChars = 3500) {
  const values = [...items];
  const kept = [];
  let chars = 0;
  for (const item of values) {
    const text = typeof item === "string" ? item : JSON.stringify(item);
    if (kept.length >= maxItems || chars + text.length > maxChars) break;
    kept.push(item);
    chars += text.length;
  }
  return {
    items: kept,
    omittedCount: values.length - kept.length,
    ...(values.length > kept.length ? { rawLocator } : {}),
  };
}

function summaryWithinLimit(summary, maxBytes = DEFAULT_SUMMARY_BYTES) {
  if (!Number.isInteger(maxBytes) || maxBytes < 512) fail("summary byte limit must be an integer >= 512", "E_SUMMARY_LIMIT");
  const initial = JSON.stringify(summary);
  if (Buffer.byteLength(initial, "utf8") <= maxBytes) return { summary, text: initial };
  const copy = JSON.parse(JSON.stringify(summary));
  const trimArray = (holder, key) => {
      if (holder?.[key] && holder[key].length > 4) {
      const all = holder[key];
      holder[key] = all.slice(0, 4);
      holder.omittedCount = (holder.omittedCount || 0) + all.length - 4;
    }
  };
  trimArray(copy.unexpectedPaths, "items");
  trimArray(copy.diagnostics, "items");
  trimArray(copy.unchangedExistingDirty, "items");
  if (Array.isArray(copy.rawPaths)) copy.rawPaths = copy.rawPaths.slice(0, 8);
  if (Array.isArray(copy.coverageLimits)) copy.coverageLimits = copy.coverageLimits.slice(0, 3);
  if (Array.isArray(copy.validators)) copy.validators = copy.validators.map((item) => ({
    name: item.name,
    status: item.status,
    exitCode: item.exitCode,
    stdoutPath: item.stdoutPath,
    stderrPath: item.stderrPath,
    stdoutBytes: item.stdoutBytes,
    stderrBytes: item.stderrBytes,
    logDrainTimedOut: item.logDrainTimedOut,
  }));
  let text = JSON.stringify(copy);
  if (Buffer.byteLength(text, "utf8") <= maxBytes) return { summary: copy, text };
  const minimal = {
    schemaVersion: SUMMARY_SCHEMA,
    command: summary.command,
    status: summary.status,
    sessionVerification: summary.sessionVerification,
    summaryPath: summary.summaryPath,
    detailsPath: summary.detailsPath,
    counts: summary.counts,
    coverageLimits: summary.coverageLimits,
    unexpectedPaths: {
      items: [],
      omittedCount: summary.counts?.unexpected || 0,
      rawLocator: summary.unexpectedPaths?.rawLocator,
    },
    diagnostics: {
      items: [],
      omittedCount: summary.counts?.diagnostics || 0,
      rawLocator: summary.diagnostics?.rawLocator,
    },
    rawPaths: summary.rawPaths,
  };
  text = JSON.stringify(minimal);
  if (Buffer.byteLength(text, "utf8") > maxBytes) {
    minimal.rawPaths = [];
    minimal.coverageLimits = [];
    text = JSON.stringify(minimal);
  }
  if (Buffer.byteLength(text, "utf8") > maxBytes) fail("summary cannot fit the requested byte limit", "E_SUMMARY_LIMIT");
  return { summary: minimal, text };
}

async function writeSummary(artifactDir, root, artifactRelative, summary, maxBytes) {
  const full = { ...summary, detailsPath: `${artifactRelative}/details.json` };
  await fsp.writeFile(path.join(artifactDir, "details.json"), `${JSON.stringify(full, null, 2)}\n`, { flag: "wx" });
  const limit = maxBytes ?? DEFAULT_SUMMARY_BYTES;
  const bounded = summaryWithinLimit(full, Math.max(512, limit - 1));
  if (Buffer.byteLength(bounded.text + "\n") > limit) fail("summary plus newline exceeds requested byte limit", "E_SUMMARY_LIMIT");
  await fsp.writeFile(path.join(artifactDir, "summary.json"), `${bounded.text}\n`, { flag: "wx" });
  return bounded.summary;
}

async function captureGit(root, artifactDir) {
  const names = {
    status: ["git-status.porcelain.z", "git-status.stderr.log"],
    unstaged: ["git-diff.unstaged.patch", "git-diff.unstaged.stderr.log"],
    staged: ["git-diff.staged.patch", "git-diff.staged.stderr.log"],
  };
  const calls = [
    ["status", ["status", "--porcelain=v1", "-z", "--untracked-files=all"]],
    ["unstaged", ["diff", "--no-ext-diff", "--binary", "--full-index"]],
    ["staged", ["diff", "--cached", "--no-ext-diff", "--binary", "--full-index"]],
  ];
  const results = {};
  for (const [label, args] of calls) {
    results[label] = await runCapture("git", ["--no-optional-locks", ...args], {
      cwd: root,
      stdoutPath: path.join(artifactDir, names[label][0]),
      stderrPath: path.join(artifactDir, names[label][1]),
      timeoutMs: DEFAULT_TIMEOUT_MS,
    });
  }
  const statusBuffer = await fsp.readFile(path.join(artifactDir, names.status[0]));
  return { results, statusBuffer, names };
}

function validatorConfig(value) {
  if (!value || typeof value !== "object" || Array.isArray(value)) fail("validator must be an object", "E_VALIDATOR_CONFIG");
  if (typeof value.executable !== "string" || value.executable.length === 0) fail("validator executable is required", "E_VALIDATOR_CONFIG");
  if (!Array.isArray(value.args) || value.args.some((arg) => typeof arg !== "string")) fail("validator args must be an array of strings", "E_VALIDATOR_CONFIG");
  return {
    name: typeof value.name === "string" && value.name ? value.name : value.executable,
    executable: value.executable,
    args: [...value.args],
    cwd: value.cwd,
  };
}

async function loadValidators(root, options) {
  const values = [];
  if (options.validatorsFile) {
    const raw = JSON.parse((await readOwnedFile(root, options.validatorsFile, "validators file")).toString("utf8"));
    const list = Array.isArray(raw) ? raw : raw?.validators;
    if (!Array.isArray(list)) fail("validators file must contain an array or { validators: [] }", "E_VALIDATOR_CONFIG");
    values.push(...list);
  }
  if (options.validatorJson) {
    for (const raw of options.validatorJson) values.push(JSON.parse(raw));
  }
  return values.map(validatorConfig);
}

function validatorCwd(root, cwd) {
  if (cwd === undefined || cwd === null || cwd === "") return root;
  const rel = assertRelativeInput(cwd, "validator cwd");
  const absolute = absoluteFromRelative(root, rel);
  assertInside(root, absolute, "validator cwd");
  return absolute;
}

async function runGate(options) {
  const root = await gitRoot(await realDirectory(options.root, "root"));
  const baselineRelative = assertRelativeInput(options.baseline, "baseline");
  const baseline = JSON.parse((await readOwnedFile(root, baselineRelative, "baseline")).toString("utf8"));
  if (baseline.schemaVersion !== SNAPSHOT_SCHEMA) fail("baseline is not a dd-efficiency snapshot", "E_BASELINE");
  if (path.resolve(baseline.repoRoot) !== path.resolve(root)) fail("baseline belongs to a different repository root", "E_BASELINE");
  const allowlist = normalizeAllowlist(options.allow);
  const exclusions = [baselineRelative];
  const artifactRelative = assertRelativeInput(options.artifactDir || `.dd-efficiency/runs/gate-${Date.now()}-${process.pid}-${crypto.randomBytes(3).toString("hex")}`, "artifact directory");
  for (const exclusion of options.exclude || []) exclusions.push(assertRelativeInput(exclusion, "exclusion"));
  for (const entry of allowlist) {
    if (pathOverlaps(entry, artifactRelative)) fail(`artifact directory overlaps allowlist entry: ${artifactRelative} / ${entry}`, "E_SCOPE_OVERLAP");
  }
  for (const exclusion of exclusions) {
    if (allowlist.some((entry) => pathOverlaps(entry, exclusion))) fail(`exclusion overlaps allowlist: ${exclusion}`, "E_SCOPE_OVERLAP");
    if (pathOverlaps(exclusion, artifactRelative) && exclusion !== artifactRelative) {
      fail(`artifact directory overlaps an input exclusion: ${artifactRelative} / ${exclusion}`, "E_SCOPE_OVERLAP");
    }
  }
  // The fresh helper subtree is an explicit, narrowly recorded exclusion.
  // It is added only after overlap checks so an allowlist can never hide it.
  exclusions.push(artifactRelative);
  const validators = await loadValidators(root, options);
  const artifactDir = await createFreshDirectory(root, artifactRelative);
  const validatorResults = [];
  for (let index = 0; index < validators.length; index += 1) {
    const validator = validators[index];
    const prefix = `validator-${String(index + 1).padStart(2, "0")}`;
    const cwd = validatorCwd(root, validator.cwd);
    if (validator.cwd) await assertNoReparseCrossing(root, validator.cwd, { allowMissing: false, includeFinal: true });
    const result = await runCapture(validator.executable, validator.args, {
      cwd,
      stdoutPath: path.join(artifactDir, `${prefix}.stdout.log`),
      stderrPath: path.join(artifactDir, `${prefix}.stderr.log`),
      timeoutMs: options.timeoutMs,
    });
    validatorResults.push({
      name: validator.name, status: result.spawnError || result.timedOut || result.logDrainTimedOut || result.code !== 0 ? "FAIL" : "PASS",
      exitCode: result.code, signal: result.signal, spawnError: result.spawnError, timedOut: result.timedOut,
      logDrainTimedOut: result.logDrainTimedOut,
      stdoutBytes: result.stdoutBytes, stderrBytes: result.stderrBytes,
      stdoutPreview: result.stdoutPreview, stderrPreview: result.stderrPreview,
      stdoutPath: `${artifactRelative}/${prefix}.stdout.log`, stderrPath: `${artifactRelative}/${prefix}.stderr.log`,
      processTreeTermination: result.processTreeTermination,
    });
  }
  const captured = await captureGit(root, artifactDir);
  const current = await inventory(root, { statusBuffer: captured.statusBuffer });
  const currentIdentity = await gitIdentity(root);
  const allPaths = new Set([...Object.keys(baseline.files || {}), ...current.files, ...await scopedFiles(root, allowlist)]);
  const changed = [];
  const unchangedExistingDirty = [];
  const diagnostics = [];
  const fingerprintChanges = [];
  for (const relative of [...allPaths].sort()) {
    if (exclusions.some((exclusion) => pathMatches(relative, exclusion))) continue;
    const before = baseline.files?.[relative] || { kind: "missing" };
    const after = await fingerprint(root, relative);
    if (["error", "directory", "special"].includes(after.kind)) diagnostics.push(`${relative}: unsupported fingerprint ${after.kind}: ${after.error || ""}`);
    if (!fingerprintsEqual(before, after)) {
      changed.push(relative);
      fingerprintChanges.push({ path: relative, before, after });
    } else if ((baseline.status?.dirtyPaths || []).includes(relative)) {
      unchangedExistingDirty.push(relative);
    }
  }
  const unexpected = changed.filter((relative) => !allowlist.some((entry) => pathMatches(relative, entry)));
  const allowedChanged = changed.filter((relative) => !unexpected.includes(relative));
  const identityFailures = [];
  for (const field of ["head", "branch", "indexHash"]) {
    if ((baseline.git?.[field] ?? null) !== (currentIdentity[field] ?? null)) {
      identityFailures.push(`${field}: expected ${baseline.git?.[field] ?? "null"}, current ${currentIdentity[field] ?? "null"}`);
    }
  }
  await fsp.writeFile(path.join(artifactDir, "fingerprint-changes.json"), `${JSON.stringify(fingerprintChanges, null, 2)}\n`, { flag: "wx" });
  const rawUnexpected = posixPath(path.join(artifactRelative, "unexpected-paths.json"));
  const rawDiagnostics = posixPath(path.join(artifactRelative, "diagnostics.json"));
  const rawIdentityFailures = posixPath(path.join(artifactRelative, "identity-failures.json"));
  const rawUnchangedDirty = posixPath(path.join(artifactRelative, "unchanged-dirty.json"));
  await fsp.writeFile(absoluteFromRelative(root, rawUnexpected), `${JSON.stringify(unexpected, null, 2)}\n`, { flag: "wx" });
  await fsp.writeFile(absoluteFromRelative(root, rawDiagnostics), `${JSON.stringify(diagnostics, null, 2)}\n`, { flag: "wx" });
  await fsp.writeFile(absoluteFromRelative(root, rawIdentityFailures), `${JSON.stringify(identityFailures, null, 2)}\n`, { flag: "wx" });
  await fsp.writeFile(absoluteFromRelative(root, rawUnchangedDirty), `${JSON.stringify(unchangedExistingDirty, null, 2)}\n`, { flag: "wx" });
  const failedValidators = validatorResults.filter((item) => item.status !== "PASS");
  const gitCaptureFailure = Object.entries(captured.results)
    .filter(([, result]) => result.spawnError || result.timedOut || result.logDrainTimedOut || result.code !== 0)
    .map(([label, result]) => `${label}: ${result.spawnError?.message || result.signal || result.code}`);
  const status = unexpected.length === 0 && diagnostics.length === 0 && identityFailures.length === 0 && failedValidators.length === 0 && gitCaptureFailure.length === 0 ? "PASS" : "FAIL";
  const summary = {
    schemaVersion: SUMMARY_SCHEMA,
    command: "gate",
    status,
    repoRoot: root,
    counts: {
      changed: changed.length,
      allowedChanged: allowedChanged.length,
      unexpected: unexpected.length,
      unchangedExistingDirty: unchangedExistingDirty.length,
      identityFailures: identityFailures.length,
      validators: validatorResults.length,
      validatorFailures: failedValidators.length,
      diagnostics: diagnostics.length,
    },
    allowlist,
    exclusions,
    identityFailures: boundedItems(identityFailures, rawIdentityFailures),
    unexpectedPaths: boundedItems(unexpected, rawUnexpected),
    unchangedExistingDirty: boundedItems(unchangedExistingDirty, rawUnchangedDirty),
    diagnostics: boundedItems(diagnostics, rawDiagnostics),
    validators: validatorResults,
    gitCaptureFailure,
    coverageLimits: [
      "Ignored paths outside explicitly checked scopes are not covered; this is not a whole-filesystem guarantee.",
      "Process-tree termination is child-only; provider/adapters must enforce their own tree watchdog where needed.",
    ],
    rawPaths: [
      posixPath(path.join(artifactRelative, "git-status.porcelain.z")),
      posixPath(path.join(artifactRelative, "git-status.stderr.log")),
      posixPath(path.join(artifactRelative, "git-diff.unstaged.patch")),
      posixPath(path.join(artifactRelative, "git-diff.unstaged.stderr.log")),
      posixPath(path.join(artifactRelative, "git-diff.staged.patch")),
      posixPath(path.join(artifactRelative, "git-diff.staged.stderr.log")),
      rawUnexpected,
      rawDiagnostics,
      rawIdentityFailures,
      rawUnchangedDirty,
      `${artifactRelative}/fingerprint-changes.json`,
    ],
    artifactDir: artifactRelative,
    summaryPath: posixPath(path.join(artifactRelative, "summary.json")),
  };
  return writeSummary(artifactDir, root, artifactRelative, summary, options.maxSummaryBytes);
}

function extractSessionRefs(result) {
  const fields = ["sessionId", "threadId", "conversationId", "sessionRef", "session_ref"];
  const refs = [];
  for (const field of fields) if (typeof result?.[field] === "string") refs.push({ field, value: result[field] });
  return refs;
}

function validateResultArtifact(value) {
  if (!value || typeof value !== "object" || Array.isArray(value)) return { valid: false, reason: "result is not an object" };
  if (typeof value.status !== "string") return { valid: false, reason: "result.status is missing" };
  const status = value.status.toLowerCase();
  if (NONTERMINAL_STATUSES.has(status)) return { valid: false, reason: `result is nonterminal: ${value.status}`, nonterminal: true };
  if (!TERMINAL_STATUSES.has(status)) return { valid: false, reason: `unknown result status: ${value.status}` };
  if (!Number.isInteger(value.exitCode)) return { valid: false, reason: "result.exitCode must be an integer" };
  if (status === "completed" && value.exitCode !== 0) return { valid: false, reason: "completed result has nonzero exitCode" };
  return { valid: true, status };
}

async function runAdapter(options) {
  const root = await realDirectory(options.root, "root");
  if (typeof options.adapter !== "string" || options.adapter.length === 0) fail("adapter executable is required", "E_ADAPTER");
  if (!Array.isArray(options.args) || options.args.some((arg) => typeof arg !== "string")) fail("adapter args must be an array of strings", "E_ADAPTER");
  const resultRelative = assertRelativeInput(options.result, "result artifact");
  const artifactRelative = assertRelativeInput(options.artifactDir || `.dd-efficiency/runs/run-${Date.now()}-${process.pid}-${crypto.randomBytes(3).toString("hex")}`, "artifact directory");
  if (pathOverlaps(resultRelative, artifactRelative)) fail(`adapter result overlaps helper artifact directory: ${resultRelative} / ${artifactRelative}`, "E_SCOPE_OVERLAP");
  await assertNoReparseCrossing(root, resultRelative, { allowMissing: true, includeFinal: true });
  const resultAbsolute = absoluteFromRelative(root, resultRelative);
  let preexisting = false;
  try {
    await fsp.lstat(resultAbsolute);
    preexisting = true;
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  const artifactDir = await createFreshDirectory(root, artifactRelative);
  if (preexisting) {
    const summary = {
      schemaVersion: SUMMARY_SCHEMA,
      command: "run",
      status: "FAIL",
      dispatchCount: 0,
      reason: "stale pre-existing result artifact; refusing to dispatch",
      resultPath: resultRelative,
      artifactDir: artifactRelative,
      rawPaths: [],
      summaryPath: posixPath(path.join(artifactRelative, "summary.json")),
    };
    return writeSummary(artifactDir, root, artifactRelative, summary, options.maxSummaryBytes);
  }
  const processResult = await runCapture(options.adapter, options.args, {
    cwd: root,
    stdoutPath: path.join(artifactDir, "adapter.stdout.log"),
    stderrPath: path.join(artifactDir, "adapter.stderr.log"),
    timeoutMs: options.timeoutMs,
  });
  let parsed = null;
  let resultError = null;
  try {
    await assertNoReparseCrossing(root, resultRelative, { allowMissing: false, includeFinal: true });
    const stat = await fsp.lstat(resultAbsolute);
    if (stat.isSymbolicLink() || !stat.isFile()) resultError = "result artifact is not a regular file";
    else parsed = JSON.parse((await fsp.readFile(resultAbsolute)).toString("utf8"));
  } catch (error) {
    resultError = error.code === "ENOENT" ? "missing result artifact" : `malformed result artifact: ${error.message}`;
  }
  const resultValidity = parsed ? validateResultArtifact(parsed) : { valid: false, reason: resultError };
  const sessionRefs = parsed ? extractSessionRefs(parsed) : [];
  const expectedSession = options.expectedSession || null;
  const sessionMatch = expectedSession === null || sessionRefs.some((item) => item.value === expectedSession);
  const failureReasons = [];
  if (processResult.spawnError) failureReasons.push(`adapter spawn failed: ${processResult.spawnError.message}`);
  if (processResult.timedOut) failureReasons.push("adapter timeout");
  if (processResult.logDrainTimedOut) failureReasons.push("log drain timed out; raw logs may be incomplete and descendants may still be running");
  if (processResult.code !== 0) failureReasons.push(`adapter exit code ${processResult.code ?? processResult.signal ?? "unknown"}`);
  if (!resultValidity.valid) failureReasons.push(resultValidity.reason || "invalid result artifact");
  if (resultValidity.valid && resultValidity.status !== "completed") failureReasons.push(`adapter status ${parsed.status}`);
  if (!sessionMatch) failureReasons.push(`expected session ${expectedSession} was not found in explicit provider fields`);
  const status = failureReasons.length === 0 ? "PASS" : "FAIL";
  const rawPaths = [
    posixPath(path.join(artifactRelative, "adapter.stdout.log")),
    posixPath(path.join(artifactRelative, "adapter.stderr.log")),
    resultRelative,
  ];
  const summary = {
    schemaVersion: SUMMARY_SCHEMA,
    command: "run",
    status,
    dispatchCount: 1,
    adapter: options.adapter,
    argumentCount: options.args.length,
    resultPath: resultRelative,
    expectedSession,
    sessionVerification: expectedSession === null ? "not_requested" : sessionMatch ? "matched" : "mismatch",
    terminalResult: parsed ? { status: parsed.status, exitCode: parsed.exitCode ?? null, sessionRefs } : null,
    process: {
      exitCode: processResult.code,
      signal: processResult.signal,
      timedOut: processResult.timedOut,
      logDrainTimedOut: processResult.logDrainTimedOut,
      stdoutBytes: processResult.stdoutBytes,
      stderrBytes: processResult.stderrBytes,
      stdoutPreview: processResult.stdoutPreview,
      stderrPreview: processResult.stderrPreview,
      processTreeTermination: processResult.processTreeTermination,
    },
    failureReasons,
    coverageLimits: [
      "The helper awaits the owned child process; descendant termination is not guaranteed. A 5-second post-exit log-drain timeout fails with potentially incomplete logs.",
      ...(expectedSession === null ? ["Session continuity was not checked; this result cannot satisfy the workflow's exact-session gate."] : []),
    ],
    rawPaths,
    artifactDir: artifactRelative,
    summaryPath: posixPath(path.join(artifactRelative, "summary.json")),
  };
  return writeSummary(artifactDir, root, artifactRelative, summary, options.maxSummaryBytes);
}

async function walkFiles(root, relative) {
  const absolute = absoluteFromRelative(root, relative);
  const files = [];
  const visit = async (current, currentRelative) => {
    const entries = await fsp.readdir(current, { withFileTypes: true });
    for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
      const nextRelative = currentRelative ? `${currentRelative}/${entry.name}` : entry.name;
      const next = path.join(current, entry.name);
      const stat = await fsp.lstat(next);
      if (stat.isSymbolicLink()) continue;
      if (stat.isDirectory()) await visit(next, nextRelative);
      else if (stat.isFile()) files.push(nextRelative);
    }
  };
  await visit(absolute, posixPath(relative));
  return files;
}

function markdownTarget(fromRelative, toRelative) {
  const fromDir = path.posix.dirname(fromRelative);
  const target = path.posix.relative(fromDir, toRelative);
  return target.split("/").map((part) => encodeURIComponent(part)).join("/");
}

function indexCategory(relative) {
  const base = path.posix.basename(relative).toLowerCase();
  if (/(^|\/)(raw|runs)(\/|$)/i.test(relative) || /^planner\d*-run/.test(base)) return "raw run artifacts";
  if (base === "state.json") return "state";
  if (base.includes("authorization")) return "authorizations";
  if (/^plan[.-]/.test(base)) return "plans";
  if (base.includes("brief")) return "briefs";
  if (base.includes("decision")) return "decisions";
  if (base.includes("debate")) return "debates";
  return "other records";
}

async function buildIndex(options) {
  const root = await realDirectory(options.root, "root");
  const recordsRelative = assertRelativeInput(options.records, "records root");
  await assertNoReparseCrossing(root, recordsRelative, { allowMissing: false, includeFinal: true });
  const recordsAbsolute = absoluteFromRelative(root, recordsRelative);
  const recordsStat = await fsp.lstat(recordsAbsolute);
  if (!recordsStat.isDirectory()) fail(`records root is not a directory: ${recordsRelative}`, "E_RECORDS");
  const outputRelative = assertRelativeInput(options.out, "index output");
  const files = (await walkFiles(root, recordsRelative)).filter((relative) => relative !== outputRelative).sort();
  const groups = new Map();
  for (const relative of files) {
    const category = indexCategory(relative);
    if (!groups.has(category)) groups.set(category, []);
    groups.get(category).push(relative);
  }
  const lines = [
    GENERATED_INDEX_MARKER,
    "# Deliberate Delegate record index",
    "",
    "> Generated navigation only; this file is non-authoritative. Consult the governing immutable records and direct human authorization. Raw provider results are evidence, never permission.",
    "",
    `Selected records root: \`${recordsRelative}\``,
    `Generated at: ${new Date().toISOString()}`,
    "",
  ];
  const order = ["state", "authorizations", "plans", "briefs", "decisions", "debates", "raw run artifacts", "other records"];
  for (const category of order) {
    const entries = groups.get(category) || [];
    if (entries.length === 0) continue;
    lines.push(`## ${category[0].toUpperCase()}${category.slice(1)}`, "");
    if (category === "state") lines.push("`state.json` is a mutable pointer and cannot authorize any transition.", "");
    for (const relative of entries) {
      const target = markdownTarget(outputRelative, relative);
      lines.push(`- [${relative}](${target})`);
    }
    lines.push("");
  }
  const content = `${lines.join("\n")}\n`;
  await writeGeneratedIndex(root, outputRelative, content);
  return {
    schemaVersion: SUMMARY_SCHEMA,
    command: "index",
    status: "PASS",
    generatedIndex: outputRelative,
    recordsRoot: recordsRelative,
    linkedFiles: files.length,
    immutableBytesChanged: false,
  };
}

function parseArgs(argv) {
  const options = {};
  const positionals = [];
  const repeat = new Set(["allow", "exclude", "validator-json", "arg"]);
  const known = new Set(["root", "out", "baseline", "allow", "exclude", "validator-json", "arg", "validators", "artifact-dir", "timeout-ms", "max-summary-bytes", "adapter", "args-json", "result", "expected-session", "records"]);
  for (let index = 0; index < argv.length; index += 1) {
    const token = argv[index];
    if (!token.startsWith("--")) {
      positionals.push(token);
      continue;
    }
    const raw = token.slice(2);
    const equals = raw.indexOf("=");
    const rawKey = equals >= 0 ? raw.slice(0, equals) : raw;
    if (!known.has(rawKey)) fail(`unknown option --${rawKey}`, "E_ARGS");
    const key = rawKey === "validators" ? "validatorsFile" : rawKey.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());
    const value = equals >= 0 ? raw.slice(equals + 1) : argv[++index];
    if (value === undefined) fail(`missing value for --${key}`, "E_ARGS");
    if (repeat.has(rawKey)) {
      if (!options[key]) options[key] = [];
      options[key].push(value);
    } else options[key] = value;
  }
  options.positionals = positionals;
  return options;
}

function parseJsonArgs(value, label) {
  if (!value) return [];
  const parsed = JSON.parse(value);
  if (!Array.isArray(parsed) || parsed.some((item) => typeof item !== "string")) fail(`${label} must be a JSON array of strings`, "E_ARGS");
  return parsed;
}

async function cli(argv = process.argv.slice(2)) {
  const [command, ...rest] = argv;
  if (!command || command === "help" || command === "--help") {
    process.stdout.write([
      "dd-efficiency commands:",
      "  snapshot --root <repo> --out <relative-json> [--allow <checked-scope>]",
      "  gate --root <repo> --baseline <relative-json> --allow <path> [--allow <dir>] [--validators <relative-json>]",
      "       [--artifact-dir <fresh-relative-dir>] [--timeout-ms <n>]",
      "  run --root <project> --adapter <executable> --args-json <json-array> --result <relative-json>",
      "      [--expected-session <id>] [--artifact-dir <fresh-relative-dir>] [--timeout-ms <n>]",
      "  index --root <project> --records <relative-dir> --out <generated-relative-md>",
    ].join("\n") + "\n");
    return 0;
  }
  const options = parseArgs(rest);
  options.root = options.root || process.cwd();
  options.timeoutMs = options.timeoutMs === undefined ? DEFAULT_TIMEOUT_MS : Number(options.timeoutMs);
  options.maxSummaryBytes = options.maxSummaryBytes === undefined ? DEFAULT_SUMMARY_BYTES : Number(options.maxSummaryBytes);
  if (!Number.isFinite(options.timeoutMs) || options.timeoutMs < 0) fail("timeout-ms must be a non-negative number", "E_ARGS");
  if (!Number.isFinite(options.maxSummaryBytes)) fail("max-summary-bytes must be numeric", "E_ARGS");
  let result;
  if (command === "snapshot") {
    const root = await gitRoot(await realDirectory(options.root, "root"));
    const out = options.out || `.dd-efficiency/snapshots/snapshot-${Date.now()}-${process.pid}.json`;
    const relative = assertRelativeInput(out, "snapshot output");
    const data = await snapshotData(root, { allow: options.allow || [] });
    await writeNewFile(root, relative, `${JSON.stringify(data, null, 2)}\n`);
    result = { schemaVersion: SUMMARY_SCHEMA, command, status: "PASS", snapshotPath: relative, fileCount: Object.keys(data.files).length, repoRoot: root };
  } else if (command === "gate") {
    options.allow = options.allow || [];
    result = await runGate(options);
  } else if (command === "run") {
    options.adapter = options.adapter;
    options.args = parseJsonArgs(options.argsJson, "args-json");
    if (options.args.length === 0 && options.arg) options.args = options.arg;
    result = await runAdapter(options);
  } else if (command === "index") {
    if (!options.records || !options.out) fail("index requires --records and --out", "E_ARGS");
    result = await buildIndex(options);
  } else fail(`unknown command: ${command}`, "E_ARGS");
  process.stdout.write(`${JSON.stringify(result)}\n`);
  return result.status === "PASS" ? 0 : 1;
}

